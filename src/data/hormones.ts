export interface Result {
  condition: Condition;
  score: number;
  /** 0–1: доля от максимально возможного балла по этой причине. */
  match: number;
  level: 'высокая' | 'средняя' | 'низкая';
}

/** Подобрать возможные причины по выбранным симптомам (самые вероятные сверху). */
export function analyze(selected: Set<string>): Result[] {
  const out: Result[] = [];
  for (const c of CONDITIONS) {
    const max = Object.values(c.weights).reduce((a, b) => a + b, 0);
    let score = 0;
    for (const [s, w] of Object.entries(c.weights)) if (selected.has(s)) score += w;
    if (!score) continue;
    const match = score / max;
    const level = score >= 5 && match >= 0.35 ? 'высокая' : score >= 3 ? 'средняя' : 'низкая';
    out.push({ condition: c, score, match, level });
  }
  return out.sort((a, b) => b.score - a.score || b.match - a.match);
}
